E = html.escape

def L(*parts):
    """L('оқушы','h:мын') -> lego; r=root default, h=hard, s=soft, y=yellow connector, g=grey"""
    out = []
    for i, p in enumerate(parts):
        if ':' in p:
            k, t = p.split(':', 1)
        else:
            k, t = ('r' if i == 0 else 'h'), p
        out.append(f'<span class="{k}">{E(t)}</span>')
    return '<span class="lego">' + ''.join(out) + '</span>'

def eq(lego, phrase, ru):
    return f'<div class="eq">{lego}<span>=</span><span><span class="ph">{E(phrase)}</span> <span class="spk">🔊</span><br><span class="ru">{E(ru)}</span></span></div>'

def joke(t):
    return f'<div class="joke">{t}</div>'

def tiles(a, b):
    return f'<div class="two">{a}{b}</div>'

def tile(kind, title, lego, small):
    return f'<div class="tile {kind}"><b>{title}</b>{lego}<small>{small}</small></div>'

def chars(rows):
    h = ''.join(f'<div class="ch"><span class="e">{e}</span><span><b>{t}</b><small>{sm}</small></span><span class="tails">{tl}</span></div>' for e, t, sm, tl in rows)
    return f'<div class="chars">{h}</div>'

def tl(h, s):
    return f'<i class="ih">{E(h)}</i><i class="is">{E(s)}</i>'

def legos(*ls):
    return '<div class="eq" style="margin-top:9px;justify-content:space-around">' + ''.join(ls) + '</div>'

def fam(rows):
    out = []
    for p, ru, right in rows:
        out.append(f'<div class="fr"><span class="p">{E(p)}<small>{E(ru)}</small></span><span>{right}</span></div>')
    return '<div class="fam">' + ''.join(out) + '</div>'

REST = '<span class="rest">без хвостика</span>'

def trap(no, why, yes, ru):
    return f'<div class="trap"><div class="no"><s>{E(no)}</s><small>{why}</small></div><div class="yes">{E(yes)} ✅<small>{E(ru)}</small></div></div>'

def school(word, text):
    return f'<div class="school"><div class="w">{E(word)}</div><p>{text}</p></div>'

def table(head, rows):
    th = ''.join(f'<th>{h}</th>' for h in head)
    tr = ''.join('<tr>' + ''.join(f'<td{(" class=" + chr(34) + c[0] + chr(34)) if isinstance(c, tuple) else ""}{(" colspan=" + chr(34) + str(c[2]) + chr(34)) if isinstance(c, tuple) and len(c) > 2 else ""}>{c[1] if isinstance(c, tuple) else c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table style="margin-top:8px"><tr>{th}</tr>{tr}</table>'

def hs(h, s):
    return f'<span style="color:var(--hard)">{E(h)}</span> / <span style="color:var(--soft)">{E(s)}</span>'

def cheat(t='📋 Шпаргалка — все хвостики'):
    return '<p style="margin:10px 0 2px;font:800 13px var(--body);color:#0c447c;text-align:center">'+t+'</p>'

def page(badge, title, bubble, blocks):
    cls = ['b1', 'b2', 'b3', 'b4', 'b5', 'b6', 'b8']
    body = ''
    for i, (h, content) in enumerate(blocks):
        body += f'<div class="blk {cls[i]}"><h2><span class="n">{i+1}</span>{h}</h2>{content}</div>'
    return f'''<!DOCTYPE html><html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>{E(title)}</title><style>{CSS}</style></head><body><div class="book">
<div class="top"><div class="ico">📖</div><div><span class="badge">{E(badge)}</span><h1>{E(title)}</h1></div></div>
<div class="say"><div class="av">🤖</div><div class="bub">{bubble}</div></div>
{body}
<div class="btns"><div class="btn a">🔊 Послушать всё</div><div class="btn b">К урокам →</div></div></div></body></html>'''

