#!/usr/bin/env python3
"""Линтер текста Тілашара: прогоняет все уроки (проверки — многократно) и ищет запрещённое."""
import re,subprocess,sys
N={0:9,1:7,2:6,3:8}
BAD=[(r'жиырма|отыз|қырық|\bелу\b|алпыс|жетпіс|сексен|тоқсан','десятки по-казахски'),
     (r'\bон (бір|екі|үш|төрт|бес|алты|жеті|сегіз|тоғыз)\b','11–19 по-казахски'),
     (r'одиннадцать|двенадцать|тринадцать|четырнадцать|пятнадцать|шестнадцать|семнадцать|восемнадцать|девятнадцать|двадцать|тридцать|сорок|пятьдесят','десятки по-русски'),
     (r'\b(1[1-9]|[2-9]\d) (огур|яблок|груш|арбуз|абрикос|морков|помидор|картоф|лук|дын)','число >10 у товара'),
     (r'қауын|бургер|телефон|зебра|жалқау|ашулы','непройденное/неказахское/негатив'),
     (r'Үлкен робот|зат есім|сын есім','запрещённое'),
     (r'undefined|NaN|\[object','поломка шаблона')]
bad=0
for th,n in N.items():
    for l in range(n):
        reps=25 if l==n-1 else 4
        for _ in range(reps):
            out=subprocess.run(['python3','/tmp/v63/lesson.py',str(th),str(l)],capture_output=True,text=True).stdout
            for rx,why in BAD:
                for m in re.finditer(rx,out):
                    line=out[max(0,out.rfind('\n',0,m.start())):out.find('\n',m.end())].strip()
                    print(f'Т{th+1} У{l+1}: {why}: {line[:160]}');bad+=1
print('ЧИСТО' if not bad else f'НАЙДЕНО: {bad}')
sys.exit(1 if bad else 0)
